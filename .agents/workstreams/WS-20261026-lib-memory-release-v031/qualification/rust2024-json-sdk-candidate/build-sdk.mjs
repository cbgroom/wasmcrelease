import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdirSync, readFileSync, writeFileSync, copyFileSync} from 'node:fs';
import {join} from 'node:path';
const [root,out]=process.argv.slice(2);
if(!root||!out) throw Error('usage: build-sdk <installed-json-root> <new-output-directory>');
const hash=x=>createHash('sha256').update(x).digest('hex');
const rootBytes=readFileSync(join(root,'lib.json'));
assert.equal(hash(rootBytes),'d0dcc046018ac37523e079b0990e5427aac1b2220a0df5da5d4610a19dfc2af0');
const manifest=JSON.parse(rootBytes),info=manifest.bindings.rust_core;
const sdk=readFileSync(join(root,info.source.path));
assert.equal(hash(sdk),'29ace9875454531252db0d36761130950040a6e85d6aaec914bcef8a30f560bc');
assert.equal(hash(sdk),info.source.sha256);
const lib=readFileSync(join(root,manifest.artifact.path));
assert.equal(hash(lib),'09b833d6b1910ef1e345e73c9b2698deb6f78b6077e4ab31b3ed9c5e0c1e2c06');
assert.equal(info.artifact_sha256,hash(lib));
let src=sdk.toString('utf8'),externs=0,exports=0;
src=src.replace(/(?<!unsafe )extern\s+"C"\s*\{/g,()=>{externs++;return 'unsafe extern "C" {'});
src=src.replace(/#\[no_mangle\]/g,()=>{exports++;return '#[unsafe(no_mangle)]'});
assert.equal(externs,28);assert.equal(exports,26);
const output=Buffer.from(src), license=readFileSync(join(root,'LICENSE'));
mkdirSync(out,{recursive:false}); mkdirSync(join(out,'src'));
writeFileSync(join(out,'src/lib.rs'),output,{flag:'wx'});copyFileSync(join(root,'LICENSE'),join(out,'LICENSE'));
const pkg={schema:'wasmc.rust-core-sdk-edition2024-candidate/v1',status:'candidate-not-released',lib:'wasmc-json',version:'0.2.1',edition:'2024',root_manifest_sha256:hash(rootBytes),lib_artifact_sha256:hash(lib),original_sdk_sha256:hash(sdk),sdk_sha256:hash(output),license_sha256:hash(license),derivation:'exact generated Rust Core SDK, syntax-only Rust 2024 translation; not generated by the WAsmC producer',extern_blocks:externs,export_attributes:exports};
writeFileSync(join(out,'sdk.json'),JSON.stringify(pkg,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify(pkg));
