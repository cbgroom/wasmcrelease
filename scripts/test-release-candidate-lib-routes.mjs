import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const root=new URL('../',import.meta.url).pathname;
const work=mkdtempSync(join(tmpdir(),'wasmc-release-route-'));
const path=join(work,'candidate.json');
const run=(args)=>spawnSync(process.execPath,['scripts/release-candidate.mjs',...args],{cwd:root,encoding:'utf8',maxBuffer:16<<20});
const created=run(['create',path,'a'.repeat(40),'0.0.18']);
assert.equal(created.status,0,created.stderr+created.stdout);
const candidate=JSON.parse(readFileSync(path,'utf8'));
assert.equal(candidate.schema,'wasmc.release-product-candidate/v2');
assert.equal(candidate.lib_route_closure.release_packages,22);
assert.equal(candidate.lib_route_closure.package_routes,22);
assert.equal(candidate.lib_route_closure.api_routes,140);
assert.equal(candidate.lib_route_closure.candidate_extras,0);
assert.equal(candidate.lib_route_closure.exact,true);
const verified=run(['verify',path]);
assert.equal(verified.status,0,verified.stderr+verified.stdout);
console.log(JSON.stringify({accepted:true,required_schema:'wasmc.release-product-candidate/v2',release_ready:true,release_packages:22,package_routes:22,api_routes:140,candidate_extras:0,publishes:false,next:'dev-stage-qualification'}));
