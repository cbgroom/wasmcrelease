import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync,spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const read=path=>readFileSync(path,'utf8');
const quick=JSON.parse(read('agent-current-lib-quickstart.json'));
const catalogBytes=read('catalog/libs-current-v2.json'),catalog=JSON.parse(catalogBytes);
const policy=JSON.parse(read('catalog/current-v2-policy.json'));
assert.equal(quick.schema,'wasmc.current-lib-quickstart/v1');
assert.equal(quick.scope,'current-development');
assert.equal(quick.authority,'catalog/current-v2-policy.json');
assert.equal(quick.catalog,policy.catalog);
assert.equal(quick.current_package_count,catalog.packages.length);
assert.equal(quick.backlog_count,policy.rebuild_backlog_count);
assert.equal(quick.catalog_sha256,createHash('sha256').update(catalogBytes).digest('hex'));
assert.equal(quick.release_qualified,false);assert.equal(quick.selection_authority,false);
assert.equal(quick.ordinary_app_consumption_qualified,false);
assert.match(read('AGENTS.md'),/agent-current-lib-quickstart\.json/);
const selected=catalog.packages.find(row=>row.id===quick.base64_decode.id);
for(const key of ['root','version','wit_sha256','artifact_sha256'])assert.equal(quick.base64_decode[key],selected[key]);
assert.deepEqual(quick.base64_decode.required_additional_reads,[selected.root+'/SKILL.md',selected.root+'/lib.wit']);
for(const path of quick.base64_decode.required_additional_reads)assert(read(path).length>0);
for(const id of Object.keys(quick.excluded_examples)){
  assert.equal(quick.excluded_examples[id],false);assert(!catalog.packages.some(row=>row.id===id));
}
const run=args=>JSON.parse(execFileSync(process.execPath,args,{encoding:'utf8'}));
assert.equal(quick.help_command,'node scripts/wasmc-lib.mjs --help');
const help=run(['scripts/wasmc-lib.mjs','--help']);
assert.equal(help.current_development_route,'agent-current-lib-quickstart.json');
assert.equal(help.selection_authority,false);
assert.equal(quick.base64_decode.search_command,help.commands.search.example);
const hit=run(['scripts/wasmc-lib.mjs','search','base64 decode','--limit','8']).hits[0];
assert.equal(hit.identity,quick.base64_decode.api_identity);assert.equal(hit.wit_path,selected.root+'/lib.wit');
const resolveArgs=quick.base64_decode.resolve_command.split(' ');
assert.deepEqual(resolveArgs.slice(0,2),['node','scripts/wasmc-lib.mjs']);
assert.equal(run(resolveArgs.slice(1)).verified,true);
assert.notEqual(spawnSync(process.execPath,['scripts/wasmc-lib.mjs','--help','extra']).status,0);
assert.equal(quick.check_command,'node scripts/validate-current-development.mjs');
console.log(JSON.stringify({accepted:true,compact_route:true,exact_resolution:true,help:true,release_qualified:false}));
